class BaselineColor:
    """Aprende el color de piel del donante durante la calibración
    y devuelve un score de palidez relativo a ese baseline."""

    def __init__(self):
        self._buf_V = {idx: [] for idx, _ in ZONAS_PIEL}
        self._buf_S = {idx: [] for idx, _ in ZONAS_PIEL}
        self._buf_G = {idx: [] for idx, _ in ZONAS_PIEL}
        self.ref_V: dict = {}
        self.ref_S: dict = {}
        self.ref_G: dict = {}
        # EAR baseline — NUEVO v7
        self._buf_ear: list = []
        self.ear_media: float = 0.30    # valor por defecto razonable
        self.ear_std:   float = 0.03
        self.listo = False

    def _extraer_stats(self, frame, lm, idx, h, w, tam=22):
        px = int(lm[idx].x * w)
        py = int(lm[idx].y * h)
        x1 = max(0, px - tam // 2)
        y1 = max(0, py - tam // 2)
        roi = frame[y1:min(h, y1+tam), x1:min(w, x1+tam)]
        if roi.size == 0:
            return None
        hsv   = cv2.cvtColor(roi, cv2.COLOR_BGR2HSV).astype(float)
        return hsv[:,:,2].mean(), hsv[:,:,1].mean(), roi[:,:,1].astype(float).mean()

    def acumular(self, frame, lm, ear=None):
        if self.listo:
            return
        h, w = frame.shape[:2]
        for idx, _ in ZONAS_PIEL:
            stats = self._extraer_stats(frame, lm, idx, h, w)
            if stats:
                V, S, G = stats
                self._buf_V[idx].append(V)
                self._buf_S[idx].append(S)
                self._buf_G[idx].append(G)
        # Acumular EAR normal del donante
        if ear is not None and ear > 0.05:   # descartar frames con ojos cerrados
            self._buf_ear.append(ear)

    def fijar(self):
        for idx, _ in ZONAS_PIEL:
            if self._buf_V[idx]:
                self.ref_V[idx] = float(np.mean(self._buf_V[idx]))
                self.ref_S[idx] = float(np.mean(self._buf_S[idx]))
                self.ref_G[idx] = float(np.mean(self._buf_G[idx]))
        # Baseline EAR personal — NUEVO v7
        if self._buf_ear:
            self.ear_media = float(np.mean(self._buf_ear))
            self.ear_std   = float(max(np.std(self._buf_ear), 0.01))  # mínimo 0.01 para evitar σ=0
        self.listo = True
        print("Baseline color piel fijado:")
        for idx, _ in ZONAS_PIEL:
            zona = {FRENTE:"Frente", MEJILLA_IZQ:"Mej.Izq", MEJILLA_DER:"Mej.Der"}.get(idx)
            print(f"   {zona}: V={self.ref_V.get(idx,0):.1f}  "
                  f"S={self.ref_S.get(idx,0):.1f}  "
                  f"G={self.ref_G.get(idx,0):.1f}")
        print(f"Baseline EAR: media={self.ear_media:.3f}  σ={self.ear_std:.3f}  "
              f"→ umbral alerta > {self.ear_media + 2*self.ear_std:.3f}")

    def score_palidez(self, frame, lm):
        if not self.listo:
            return 0.0
        h, w = frame.shape[:2]
        score_total = peso_total = 0.0
        for idx, peso_zona in ZONAS_PIEL:
            if idx not in self.ref_V:
                continue
            stats = self._extraer_stats(frame, lm, idx, h, w)
            if stats is None:
                continue
            V_act, S_act, G_act = stats
            dV = max(0.0,  (V_act - self.ref_V[idx]) / 255.0)
            dS = max(0.0, -(S_act - self.ref_S[idx]) / 255.0)
            dG = max(0.0, -(G_act - self.ref_G[idx]) / 255.0)
            score_zona    = 0.45 * dV + 0.35 * dS + 0.20 * dG
            score_total  += score_zona * peso_zona
            peso_total   += peso_zona
        if peso_total == 0:
            return 0.0
        return float(np.clip(score_total / (peso_total * 0.25), 0.0, 1.0))

