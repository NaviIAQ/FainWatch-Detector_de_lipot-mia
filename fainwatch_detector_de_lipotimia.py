def dist(a, b):
    return np.sqrt((a.x - b.x)**2 + (a.y - b.y)**2)

def blink_score(fr):
    try:
        bl = {b.category_name: b.score for b in fr.face_blendshapes[0]}
        return (bl.get("eyeBlinkLeft", 0) + bl.get("eyeBlinkRight", 0)) / 2
    except:
        return 0.0

def apertura_boca(lm):
    return dist(lm[BOCA_SUP], lm[BOCA_INF]) / (dist(lm[BOCA_IZQ], lm[BOCA_DER]) + 1e-6)

def angulos_cabeza(lm):
    f, m, n = lm[FRENTE], lm[MENTON], lm[NARIZ_TIP]
    roll  = abs(np.degrees(np.arctan2(m.x - f.x, m.y - f.y + 1e-6)))
    eje_y = (f.y + m.y) / 2
    pitch = abs((n.y - eje_y) / (abs(m.y - f.y) + 1e-6)) * 90
    return roll, pitch

def detectar_caida(pr):
    try:
        lm    = pr.pose_landmarks[0]
        nariz = lm[POSE_NARIZ]
        y_h   = (lm[POSE_HOMBRO_IZQ].y + lm[POSE_HOMBRO_DER].y) / 2
        frontal   = max(0.0, nariz.y - y_h)
        asimetria = abs(lm[POSE_HOMBRO_IZQ].y - lm[POSE_HOMBRO_DER].y)
        return max(frontal, asimetria * 0.6)
    except:
        return 0.0

def detectar_malestar(fr):
    if not fr.face_blendshapes:
        return 0.0
    bl = {b.category_name: b.score for b in fr.face_blendshapes[0]}
    score = sum(
        bl.get(nombre, 0.0) * peso
        for nombre, peso in BLENDSHAPES_MALESTAR.items()
    )
    return float(np.clip(score / _PESO_TOTAL_MALESTAR, 0.0, 1.0))

