#   Botón TERMINAR → pone None en la cola → hilo para
# ==============================================================

import queue      as _queue
import threading  as _threading
import base64     as _base64

_cola_frames   = _queue.Queue(maxsize=4)
_sesion_activa = False


def _registrar_captura_js():
    """
    Registra la función Python que el JS llama para enviar frames.
    Debe ejecutarse UNA VEZ desde el hilo principal antes de iniciar.
    """
    from google.colab import output as _colab_output

    def _recibir_frame(data_url):
        """Llamada por el JS con cada frame en base64."""
        if not _sesion_activa:
            return
        try:
            b64 = data_url.split(',')[1]
            img = Image.open(io.BytesIO(_base64.b64decode(b64)))
            frame = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2BGR)
            try:
                _cola_frames.put_nowait(frame)
            except _queue.Full:
                pass   # detector ocupado, descartamos frame
        except Exception as e:
            pass

    _colab_output.register_callback('enviar_frame', _recibir_frame)


def _iniciar_captura_js(fps=12):
    """Arranca el bucle de captura en el navegador."""
    intervalo = int(1000 / fps)
    display(Javascript(f'''
    (function() {{
        if (window._captureTimer) clearInterval(window._captureTimer);
        const v = window._webcamVideo;
        if (!v) {{ console.warn("Cámara no disponible"); return; }}
        const c = document.createElement('canvas');
        c.width  = v.videoWidth  || 640;
        c.height = v.videoHeight || 480;
        const ctx = c.getContext('2d');
        window._captureTimer = setInterval(function() {{
            if (!window._sesionActiva) {{
                clearInterval(window._captureTimer);
                return;
            }}
            ctx.drawImage(v, 0, 0, c.width, c.height);
            const dataUrl = c.toDataURL('image/jpeg', 0.7);
            google.colab.kernel.invokeFunction('enviar_frame', [dataUrl], {{}});
        }}, {intervalo});
        console.log("Captura JS iniciada a {fps} fps");
    }})();
    '''))


def _detener_captura_js():
    """Para el bucle JS y señala parada."""
    display(Javascript('''
    window._sesionActiva = false;
    if (window._captureTimer) {
        clearInterval(window._captureTimer);
        window._captureTimer = null;
    }
    console.log("Captura JS detenida");
    '''))


def _bucle_detector(cfg, estado_lbl, salida, dh):
    """Corre en hilo secundario. Consume frames de _cola_frames."""
    global _sesion_activa

    baseline_color   = BaselineColor()
    modelos          = ModelosMP(cfg)
    detector         = DetectorLipotimia(cfg)
    detector_mirada  = DetectorMiradaFija(cfg, baseline_color)
    detector_bostezo = DetectorBostezo(cfg)
    filtro_mov       = FiltroMovimientoVoluntario(cfg)   # ← NUEVO v8
    calibrador       = Calibrador(cfg, baseline_color)
    logger           = Logger()
    t_prev           = time.time()

    with salida:
        print(f"🔴 Grabando — quédate quieto/a {cfg.frames_calibracion} frames…")

    try:
        while _sesion_activa:
            try:
                frame = _cola_frames.get(timeout=1.0)
            except _queue.Empty:
                continue

            if frame is None:
                break

            rgb    = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            mp_img = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb)
            ts     = int(time.time() * 1000)

            fr = modelos.face.detect_for_video(mp_img, ts)
            pr = modelos.pose.detect_for_video(mp_img, ts)

            blink = boca = roll = pitch = caida = palidez = malestar = 0.0
            ear = mov_iris = 0.0
            alerta_mirada = bostezo_activo = False
            lm = None

            if fr.face_landmarks:
                lm          = fr.face_landmarks[0]
                blink       = blink_score(fr)
                boca        = apertura_boca(lm)
                roll, pitch = angulos_cabeza(lm)
                malestar    = detectar_malestar(fr)
                palidez     = baseline_color.score_palidez(frame, lm)
                ear, mov_iris, alerta_mirada = detector_mirada.actualizar(lm)
                _, _, bostezo_activo = detector_bostezo.actualizar(lm, fr)

            if pr.pose_landmarks:
                caida = detectar_caida(pr)

            calibrador.agregar(frame, lm, blink, boca, roll, pitch,
                               caida, malestar, ear=ear)

            blink, boca, roll, pitch, caida, palidez, malestar = detector.filtrar(
                blink, boca, roll, pitch, caida, palidez, malestar
            )

            # v8: aplicar filtros de movimiento voluntario ANTES de evaluar
            roll_ok, pitch_ok, caida_ok, mov_rapido = filtro_mov.actualizar(
                roll, pitch, caida, cfg
            )

            nivel, alertas = detector.evaluar(
                blink, boca, palidez, malestar, alerta_mirada,
                roll_ok, pitch_ok, caida_ok, mov_rapido
            )

            now    = time.time()
            fps    = 1.0 / max(now - t_prev, 1e-6)
            t_prev = now

            e = Estado(blink, boca, roll, pitch, caida, palidez, malestar,
                       ear, mov_iris, bostezo_activo,
                       detector_bostezo.total_bostezos, nivel, alertas, fps)
            logger.escribir(e)

            dibujar(frame, e, calibrador.calibrado,
                    len(calibrador.buffer["blink"]), cfg.frames_calibracion)
            _, buf = cv2.imencode('.jpg', frame)
            dh.update(IPImage(data=buf.tobytes()))

    finally:
        modelos.cerrar()
        b = detector_bostezo.total_bostezos
        n = len(logger._registros)
        with salida:
            print(f"\n✔ Sesión terminada — {n} frames | {b} bostezos")
        logger.guardar_csv()
        logger.guardar_pdf(total_bostezos=b,
                           ultimo_bostezo=detector_bostezo.ultimo_bostezo)
        estado_lbl.value = "✔ Sesión finalizada — descarga el informe desde la carpeta de Colab"
        with salida:
            print("Panel de Archivos (barra lateral izquierda) → descarga.")


def lanzar_interfaz():
    import ipywidgets as widgets
    from IPython.display import display as ipy_display
    global _sesion_activa, _cola_frames

    CFG = Config(
        fps_objetivo=12.0,
        frames_calibracion=50,
        umbral_palidez=0.25,
        umbral_malestar=0.30,
        ear_margen_sigma=2.0,
        umbral_movimiento_iris=0.008,
        frames_mirada_fija=22,
        umbral_mar_bostezo=0.45,
        umbral_squint_bostezo=0.25,
        frames_bostezo=14,
            # v8: filtros de movimiento voluntario
            umbral_velocidad_giro=3.5,   # grados/frame; sube si hay muchos falsos positivos
            min_params_coherencia=2,     # mínimo 2 señales distintas para subir de nivel
            frames_postural_minimo=8,    # ~0.7s sostenido antes de que postura cuente
    )

    btn_iniciar  = widgets.Button(
        description="▶  INICIAR",
        button_style="success",
        layout=widgets.Layout(width="160px", height="44px"),
        style={"font_weight": "bold", "font_size": "14px"},
    )
    btn_terminar = widgets.Button(
        description="⏹  TERMINAR",
        button_style="danger",
        layout=widgets.Layout(width="160px", height="44px"),
        style={"font_weight": "bold", "font_size": "14px"},
        disabled=True,
    )
    estado_lbl = widgets.Label(value="Pulsa INICIAR para comenzar")
    salida     = widgets.Output()
    dh         = display(None, display_id=True)

    ipy_display(widgets.VBox([
        widgets.HTML("<h3 style='margin:0 0 8px 0'> Detector de Lipotimia v7f</h3>"),
        widgets.HBox([btn_iniciar, btn_terminar],
                     layout=widgets.Layout(gap="12px")),
        estado_lbl,
        salida,
    ]))

    def on_terminar(_):
        global _sesion_activa
        _sesion_activa   = False
        _detener_captura_js()
        try: _cola_frames.put_nowait(None)
        except: pass
        estado_lbl.value = "Finalizando sesión…"

    def on_iniciar(_):
        global _sesion_activa, _cola_frames
        if _sesion_activa:
            return

        # Limpiar cola
        while not _cola_frames.empty():
            try: _cola_frames.get_nowait()
            except: break

        btn_iniciar.disabled  = True
        btn_terminar.disabled = False
        estado_lbl.value      = "🔴 Grabando…"
        _sesion_activa        = True

        # Arrancar JS de captura en el navegador
        display(Javascript("window._sesionActiva = true;"))
        _iniciar_captura_js(fps=int(CFG.fps_objetivo))

        # Arrancar hilo detector
        hilo = _threading.Thread(
            target=_bucle_detector,
            args=(CFG, estado_lbl, salida, dh),
            daemon=True
        )
        hilo.start()

        def _esperar_fin():
            hilo.join()
            btn_iniciar.disabled  = False
            btn_terminar.disabled = True

        _threading.Thread(target=_esperar_fin, daemon=True).start()

    btn_iniciar.on_click(on_iniciar)
    btn_terminar.on_click(on_terminar)


