class FiltroMovimientoVoluntario:
    """
    Implementa las tres estrategias para distinguir movimiento
    voluntario (hablar, girar a mirar algo) de síntoma de lipotimia.

    Estrategia 1 — Velocidad:
        Mide el cambio de roll y pitch entre frames consecutivos.
        Un giro voluntario es rápido (ΔAngulo/frame alto).
        Un cabeceo por lipotimia es lento y progresivo.
        Si la velocidad supera umbral_velocidad_giro → se ignora
        ese frame para los parámetros posturales.

    Estrategia 2 — Coherencia:
        Cuando alguien habla, la boca está abierta pero los ojos
        están alertas, la piel tiene color normal y la postura es
        correcta. La lipotimia arrastra varios parámetros a la vez.
        Exige min_params_coherencia parámetros distintos activos
        simultáneamente antes de subir el nivel de riesgo.

    Estrategia 3 — Duración mínima:
        Un giro voluntario dura 1-3 segundos y el donante vuelve.
        Una desviación por lipotimia se mantiene o empeora.
        Los parámetros posturales (roll, pitch, caída) solo puntúan
        si llevan frames_postural_minimo frames consecutivos activos.
    """

    def __init__(self, cfg):
        self.cfg = cfg
        # Estrategia 1: velocidad
        self._roll_prev  = None
        self._pitch_prev = None
        # Estrategia 3: contadores de duración por parámetro postural
        self._frames_roll  = 0
        self._frames_pitch = 0
        self._frames_caida = 0

    def actualizar(self, roll, pitch, caida, cfg):
        """
        Devuelve (roll_ok, pitch_ok, caida_ok, movimiento_rapido).

        roll_ok / pitch_ok / caida_ok: True si el parámetro supera
        su umbral Y pasa los filtros de velocidad y duración.
        movimiento_rapido: True si el frame actual parece voluntario.
        """
        # ── Estrategia 1: velocidad ──────────────────────────────
        movimiento_rapido = False
        if self._roll_prev is not None:
            delta_roll  = abs(roll  - self._roll_prev)
            delta_pitch = abs(pitch - self._pitch_prev)
            if delta_roll > cfg.umbral_velocidad_giro or \
               delta_pitch > cfg.umbral_velocidad_giro:
                movimiento_rapido = True

        self._roll_prev  = roll
        self._pitch_prev = pitch

        # Si el movimiento es rápido, no acumulamos duración
        # y descartamos posturales este frame
        if movimiento_rapido:
            self._frames_roll  = max(0, self._frames_roll  - 1)
            self._frames_pitch = max(0, self._frames_pitch - 1)
            self._frames_caida = max(0, self._frames_caida - 1)
            return False, False, False, True

        # ── Estrategia 3: duración mínima ────────────────────────
        umbral_min = cfg.frames_postural_minimo

        if roll > cfg.umbral_roll:
            self._frames_roll += 1
        else:
            self._frames_roll = max(0, self._frames_roll - 1)

        if pitch > cfg.umbral_pitch:
            self._frames_pitch += 1
        else:
            self._frames_pitch = max(0, self._frames_pitch - 1)

        if caida > cfg.umbral_caida:
            self._frames_caida += 1
        else:
            self._frames_caida = max(0, self._frames_caida - 1)

        roll_ok  = self._frames_roll  >= umbral_min
        pitch_ok = self._frames_pitch >= umbral_min
        caida_ok = self._frames_caida >= umbral_min

        return roll_ok, pitch_ok, caida_ok, False

