class DetectorLipotimia:
    def __init__(self, cfg):
        self.cfg = cfg
        self.f = {k: EMA(cfg.alpha_ema)
                  for k in ["blink","boca","roll","pitch","caida","palidez","malestar"]}
        self.frames_ojos = 0
        self.hist = deque(maxlen=cfg.ventana_riesgo)

    def filtrar(self, blink, boca, roll, pitch, caida, palidez, malestar):
        return (
            self.f["blink"].update(blink),
            self.f["boca"].update(boca),
            self.f["roll"].update(roll),
            self.f["pitch"].update(pitch),
            self.f["caida"].update(caida),
            self.f["palidez"].update(palidez),
            self.f["malestar"].update(malestar),
        )

    def evaluar(self, blink, boca, palidez, malestar, alerta_mirada,
                roll_ok, pitch_ok, caida_ok, movimiento_rapido):
        """
        v8: recibe flags ya filtrados por FiltroMovimientoVoluntario.

        Estrategia 1 (velocidad): roll_ok/pitch_ok/caida_ok son False
          si el movimiento fue demasiado rápido (voluntario).

        Estrategia 2 (coherencia): antes de sumar puntos al nivel,
          comprueba que haya al menos min_params_coherencia señales
          distintas activas. Una sola señal aislada no sube de nivel.

        Estrategia 3 (duración): roll_ok/pitch_ok/caida_ok solo son
          True si llevan frames_postural_minimo frames consecutivos.
        """
        c = self.cfg
        alertas = []
        # Mapa señal → puntos (solo se añaden si la señal está activa)
        senales = []

        self.frames_ojos = self.frames_ojos + 1 if blink > c.umbral_blink \
                           else max(0, self.frames_ojos - 1)
        if self.frames_ojos > c.frames_ojos_umbral:
            senales.append(("OJOS CERRADOS", 3))
        if boca     > c.umbral_boca:     senales.append(("BOCA ABIERTA",   1))
        if palidez  > c.umbral_palidez:  senales.append(("PALIDEZ",        2))
        if malestar > c.umbral_malestar: senales.append(("MALESTAR",       1))
        if alerta_mirada:                senales.append(("MIRADA FIJA",    3))

        # Parámetros posturales: solo si pasan filtros velocidad+duración
        if roll_ok:  senales.append(("CABEZA LATERAL", 2))
        if pitch_ok: senales.append(("CABEZA CAIDA",   2))
        if caida_ok: senales.append(("CAIDA POSTURAL", 3))

        # ── Estrategia 2: coherencia ─────────────────────────────
        # Si hay señales pero menos de min_params_coherencia, no subimos
        # de nivel — puede ser un giro al hablar con alguien
        if len(senales) >= c.min_params_coherencia:
            puntos = sum(p for _, p in senales)
            alertas = [n for n, _ in senales]
        elif len(senales) > 0:
            # Señal aislada: la anotamos pero con 0 puntos de nivel
            puntos = 0
            alertas = [n + "*" for n, _ in senales]  # asterisco = aislada
        else:
            puntos = 0

        self.hist.append(0 if puntos == 0 else 1 if puntos <= 2 else 2)
        return int(round(np.mean(self.hist))), alertas

