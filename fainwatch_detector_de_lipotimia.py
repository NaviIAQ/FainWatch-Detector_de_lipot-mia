class DetectorBostezo:
    """
    Detecta bostezos combinando dos señales simultáneas:

      1. MAR muy alto (boca muy abierta durante varios segundos)
         El umbral es más exigente que el de 'boca abierta' del
         detector principal, para no confundir con hablar o suspirar.

      2. Ojos entrecerrados al mismo tiempo
         Blendshapes eyeSquintLeft + eyeSquintRight: el cierre
         reflejo de los ojos durante el bostezo es involuntario
         y es lo que lo distingue de abrir la boca por sorpresa
         o malestar.

    El bostezo se registra en el CSV y en el panel de pantalla
    pero NO suma puntos al nivel de riesgo de lipotimia.

    Además lleva un contador acumulado de bostezos en la sesión,
    útil para el historial (varios bostezos seguidos = fatiga).
    """

    def __init__(self, cfg):
        self.cfg             = cfg
        self._frames_activo  = 0
        self._en_bostezo     = False   # True mientras dura el bostezo actual
        self.total_bostezos  = 0       # contador acumulado de la sesión
        self.ultimo_bostezo  = "—"     # hora del último bostezo detectado

    def actualizar(self, lm, fr):
        """
        lm : face_landmarks[0]  o None
        fr : resultado detect_for_video  (para blendshapes)

        Devuelve (mar, squint, bostezo_activo).
          mar          : float — apertura de boca normalizada actual
          squint       : float — media de entrecerrado de ojos
          bostezo_activo : bool — True si hay bostezo en curso
        """
        cfg = self.cfg

        if lm is None or not fr.face_blendshapes:
            self._frames_activo = max(0, self._frames_activo - 1)
            return 0.0, 0.0, False

        # MAR desde landmarks (mismo cálculo que apertura_boca pero sin EMA)
        mar = dist(lm[BOCA_SUP], lm[BOCA_INF]) / (
              dist(lm[BOCA_IZQ], lm[BOCA_DER]) + 1e-6)

        # Entrecerrado de ojos desde blendshapes
        bl = {b.category_name: b.score for b in fr.face_blendshapes[0]}
        squint = (bl.get("eyeSquintLeft", 0.0) + bl.get("eyeSquintRight", 0.0)) / 2.0

        # Ambas condiciones simultáneas
        boca_muy_abierta  = mar    > cfg.umbral_mar_bostezo
        ojos_entrecerrados = squint > cfg.umbral_squint_bostezo

        if boca_muy_abierta and ojos_entrecerrados:
            self._frames_activo += 1
        else:
            self._frames_activo = max(0, self._frames_activo - 1)

        bostezo_confirmado = self._frames_activo >= cfg.frames_bostezo

        # Contar cada bostezo una sola vez (flanco de subida)
        if bostezo_confirmado and not self._en_bostezo:
            self._en_bostezo    = True
            self.total_bostezos += 1
            self.ultimo_bostezo  = time.strftime("%H:%M:%S")
        elif not bostezo_confirmado and self._en_bostezo:
            self._en_bostezo = False

        return mar, squint, bostezo_confirmado

