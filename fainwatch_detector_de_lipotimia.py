class DetectorMiradaFija:
    """
    Detecta la combinación clínica de alarma vagal:
      1. Ojos MUY abiertos  → EAR supera el baseline personal del donante
                               en más de 'ear_margen_sigma' desviaciones típicas
      2. Iris INMÓVIL        → desplazamiento del centro del iris
                               entre frames < umbral_movimiento_iris

    Al usar el baseline personal se eliminan los falsos positivos
    con donantes que naturalmente tienen los ojos más abiertos.
    """

    def __init__(self, cfg, baseline_color):
        self.cfg            = cfg
        self.baseline_color = baseline_color   # referencia al mismo objeto
        self._iris_prev_izq = None
        self._iris_prev_der = None
        self._frames_activo = 0
        self._ema_ear = EMA(alpha=0.4)
        self._ema_mov = EMA(alpha=0.4)

    def _ear_landmarks(self, lm, sup, inf, ext, int_):
        v = np.sqrt((lm[sup].x - lm[inf].x)**2 + (lm[sup].y - lm[inf].y)**2)
        h = np.sqrt((lm[ext].x - lm[int_].x)**2 + (lm[ext].y - lm[int_].y)**2)
        return v / (h + 1e-6)

    def _movimiento_iris(self, lm):
        ix = lm[IRIS_IZQ_CENTRO].x;  iy = lm[IRIS_IZQ_CENTRO].y
        dx = lm[IRIS_DER_CENTRO].x;  dy = lm[IRIS_DER_CENTRO].y
        if self._iris_prev_izq is None:
            self._iris_prev_izq = (ix, iy)
            self._iris_prev_der = (dx, dy)
            return None
        mov_izq = np.sqrt((ix - self._iris_prev_izq[0])**2 + (iy - self._iris_prev_izq[1])**2)
        mov_der = np.sqrt((dx - self._iris_prev_der[0])**2 + (dy - self._iris_prev_der[1])**2)
        self._iris_prev_izq = (ix, iy)
        self._iris_prev_der = (dx, dy)
        return (mov_izq + mov_der) / 2.0

    def actualizar(self, lm):
        """
        Devuelve (ear, movimiento_iris, alerta_mirada_fija).
        El umbral EAR se calcula dinámicamente desde el baseline del donante.
        """
        cfg = self.cfg

        ear_izq = self._ear_landmarks(lm, OJO_IZQ_SUP, OJO_IZQ_INF, OJO_IZQ_EXT, OJO_IZQ_INT)
        ear_der = self._ear_landmarks(lm, OJO_DER_SUP, OJO_DER_INF, OJO_DER_EXT, OJO_DER_INT)
        ear = self._ema_ear.update((ear_izq + ear_der) / 2.0)

        mov_raw = self._movimiento_iris(lm)
        if mov_raw is None:
            return ear, 0.0, False
        mov = self._ema_mov.update(mov_raw)

        # Umbral EAR dinámico: baseline + N desviaciones típicas — NUEVO v7
        umbral_ear = self.baseline_color.ear_media + cfg.ear_margen_sigma * self.baseline_color.ear_std

        ojos_muy_abiertos = ear > umbral_ear
        iris_inmovil      = mov < cfg.umbral_movimiento_iris

        if ojos_muy_abiertos and iris_inmovil:
            self._frames_activo += 1
        else:
            self._frames_activo = max(0, self._frames_activo - 1)

        alerta = self._frames_activo >= cfg.frames_mirada_fija
        return ear, mov, alerta

    def reset(self):
        self._iris_prev_izq = None
        self._iris_prev_der = None
        self._frames_activo = 0
        self._ema_ear.reset()
        self._ema_mov.reset()

